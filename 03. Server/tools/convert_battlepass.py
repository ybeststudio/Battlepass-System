# Turns the client battlepass config (locale/common/config_json/battlepass_config.json, the Anka format) into the
# plain table the game server reads (/usr/home/share/conf/battlepass.txt, game/src/battlepass_renewal.cpp).
# Both sides use the same file, so a new season only needs the json + this script.
#
#   SEASON  <kind 0 pass / 1 event> <season_id> <start> <end> <level_exp> <bonus_vnum> <bonus_count> <bonus_exp> <theme>
#   REWARD  <kind> <season_id> <level> <free_vnum> <free_count> <premium_vnum> <premium_count>
#   MISSION <kind> <season_id> <start> <mission_id> <TYPE> <target_vnum> <count> <exp>
# dates are "YYYYMMDDHHMMSS" in server time.
#
# usage: python convert_battlepass.py [config.json] [battlepass.txt]

import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "binary_unpack", "locale", "common", "config_json", "battlepass_config.json")
DST = os.path.join(HERE, "battlepass.txt")
DEFAULT_LEVEL_EXP = 20		# Anka uiBattlePass totalBattlePassExp of a normal season


def stamp(text):
	# "2026-11-01T00:00:00" or "2026-11-01" -> 20261101000000
	text = text.replace("T", " ")
	date, _, time = text.partition(" ")
	time = time or "00:00:00"
	return date.replace("-", "") + time.replace(":", "")


def main():
	src = sys.argv[1] if len(sys.argv) > 1 else SRC
	dst = sys.argv[2] if len(sys.argv) > 2 else DST
	data = json.load(io.open(src, encoding="utf-8"))
	out = ["# generated by Tools/battlepass/convert_battlepass.py from battlepass_config.json - do not edit by hand"]
	for (kind, key) in ((0, "default_battlepasses"), (1, "event_battlepasses")):
		for bp in data.get(key, []):
			if kind == 1 and not bp.get("is_activated", True):
				continue
			sid = bp["season_id"]
			bonus = bp.get("max_level_bonus_reward", {})
			out.append("SEASON\t%d\t%d\t%s\t%s\t%d\t%d\t%d\t%d\t%s" % (kind, sid, stamp(bp["start_date"]), stamp(bp["end_date"]),
				bp.get("level_exp", DEFAULT_LEVEL_EXP), bonus.get("vnum", 0), bonus.get("count", 0), bp.get("max_level_bonus_exp", 0),
				bp.get("theme", "-")))
			for (level, r) in sorted(bp.get("rewards", {}).items(), key = lambda x: int(x[0])):
				free = r.get("free", {})
				prem = r.get("premium", {})
				out.append("REWARD\t%d\t%d\t%s\t%d\t%d\t%d\t%d" % (kind, sid, level, free.get("vnum", 0), free.get("count", 0), prem.get("vnum", 0), prem.get("count", 0)))
			for (day, sched) in sorted(bp.get("quest_schedule", {}).items()):
				for m in sched.get("missions", []):
					out.append("MISSION\t%d\t%d\t%s\t%d\t%s\t%d\t%d\t%d" % (kind, sid, stamp(day), m["mission_id"], m["mission"], m.get("vnum", 0), m["count"], m["exp"]))
	io.open(dst, "w", newline = "\n").write(u"\n".join(out) + u"\n")
	print("%s: %d lines" % (dst, len(out)))


if __name__ == "__main__":
	main()
